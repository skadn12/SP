"""Independent, fail-closed semantic review of unchanged Qwen ordering items."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import urllib.request


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "h4_crossroot_ordering_batch_v5_fresh_roots"
CONFIG = Path("/root/.config/gxy-selfplay/round1_strong_judge.env")
ROOT_IDS = ["210046", "231899", "194259", "96544"]
LABELS = [f"I{i}" for i in range(1, 7)]
MODEL = "tju-llm"


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def canonical(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def read(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def save_new(path: Path, value: object) -> None:
    if path.exists():
        raise FileExistsError(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def config() -> dict:
    if CONFIG.stat().st_mode & 0o077:
        raise ValueError("judge_config_not_private")
    values = {}
    for line in CONFIG.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip("'\"")
    required = {"provider": "TJU AI", "model": MODEL,
                "base_url": "https://ai.tju.edu.cn/api/v3",
                "api_key_env": "ROUND1_STRONG_JUDGE_API_KEY"}
    if any(values.get(key) != value for key, value in required.items()):
        raise ValueError("judge_config_identity_changed")
    secret = os.environ.get(required["api_key_env"]) or values.get(required["api_key_env"])
    if not secret:
        raise ValueError("judge_secret_missing")
    return {**required, "secret": secret}


def inputs(root_id: str) -> tuple[list[dict], dict, list[dict]]:
    rows = [row for row in read(HERE / "LABEL_REBOUND_UNREVIEWED.json") if row["root_id"] == root_id]
    if not rows:
        raise ValueError(f"no_candidates:{root_id}")
    source_path = SOURCE / root_id / "source.json"
    source = read(source_path)
    report = read(HERE / "REPORT.json")
    root_report = next(row for row in report["roots"] if row["root_id"] == root_id)
    if root_report["source_sha256"] != sha(source_path.read_bytes()):
        raise ValueError(f"source_hash_changed:{root_id}")
    allowed = {check["candidate_id"] for check in root_report["checks"] if check["label_only_mechanical_candidate"]}
    if {row["candidate_id"] for row in rows} != allowed:
        raise ValueError(f"candidate_set_changed:{root_id}")
    history = read(SOURCE / root_id / "PRIOR_CANDIDATE_SUMMARY.json")["candidates"]
    return rows, source, history


def prompt(root_id: str) -> tuple[str, list[str]]:
    rows, source, history = inputs(root_id)
    turns = source["turns"]
    positions = {turn["turn_ref"]: index for index, turn in enumerate(turns)}
    candidate_data = []
    for row in rows:
        items = []
        for label in LABELS:
            entry = row["item_evidence"][label]
            index = positions[entry["turn_ref"]]
            items.append({
                "label": label, "model_written_item": row["items"][label],
                "cited_quote": entry["quote"], "claimed_status": entry["status"],
                "cited_full_turn": turns[index],
                "previous_turn": turns[index - 1] if index > 0 else None,
                "next_turn": turns[index + 1] if index + 1 < len(turns) else None,
            })
        candidate_data.append({
            "candidate_id": row["candidate_id"], "topic": row["topic"],
            "question": row["question"], "gold": row["gold"], "items": items,
        })
    compact_history = [{key: candidate.get(key) for key in
                        ("candidate_id", "question_type", "topic", "question", "evidence_refs", "item_text")}
                       for candidate in history]
    instruction = """You are an independent auditor of ordering questions generated by another model.
Do not repair, rewrite, or propose replacement text. Judge only the supplied model-written items.
For each of the six items, set supported=true ONLY if its cited quote and cited full turn directly support the whole statement, including named person, action, referent, time, status, and modality. If a neighboring turn is needed to identify an unnamed referent or event, set supported=false. Neighbors are supplied to detect ambiguity and contradiction, not to rescue missing evidence. Planned, proposed, promised, advised, and completed actions must stay distinct. Give a short concrete reason for each verdict.
For each question, set coherent=true only when six items naturally share one topic and the question's conversation-order scope is unambiguous. Set novel_vs_history=false if it substantially retests the same facts or event sequence as a historical candidate, even with different wording or anchor turns. Set distinct_within_batch=false when substantially duplicating another current candidate. Compare semantic facts, not just exact references. Fail closed on uncertainty.
Return one JSON object only: {"reviews":[{"candidate_id":"...","items":{"I1":{"supported":true,"reason":"..."},..."I6":{"supported":true,"reason":"..."}},"coherent":true,"novel_vs_history":true,"distinct_within_batch":true,"reason":"..."},...]}. Include each supplied candidate exactly once. Booleans must be JSON booleans, never strings. Do not include a general approval field. Evaluate all candidates independently, even when one item fails.
"""
    data = {"root_id": root_id, "current_candidates": candidate_data,
            "historical_candidates": compact_history}
    return instruction + "\nDATA:\n" + json.dumps(data, ensure_ascii=False), [row["candidate_id"] for row in rows]


def prepare() -> None:
    base = config()
    for suffix in ROOT_IDS:
        root_id = "cc-train-episode-" + suffix
        text, candidate_ids = prompt(root_id)
        payload = {"model": MODEL, "messages": [{"role": "user", "content": text}],
                   "temperature": 0, "max_tokens": 4096, "stream": False}
        source_path = SOURCE / root_id / "source.json"
        index = {
            "status": "PREPARED_NO_API_CALL", "root_id": root_id,
            "candidate_ids": candidate_ids, "generator_model": "Qwen/Qwen3.6-35B-A3B",
            "reviewer_provider": base["provider"], "reviewer_model_requested": MODEL,
            "endpoint": base["base_url"] + "/chat/completions",
            "temperature": 0, "max_tokens": 4096, "retry_limit": 0,
            "prompt_sha256": sha(text.encode("utf-8")), "payload_sha256": sha(canonical(payload)),
            "source_sha256": sha(source_path.read_bytes()),
            "label_candidate_file_sha256": sha((HERE / "LABEL_REBOUND_UNREVIEWED.json").read_bytes()),
            "prior_summary_sha256": sha((SOURCE / root_id / "PRIOR_CANDIDATE_SUMMARY.json").read_bytes()),
        }
        directory = HERE / "semantic_review" / root_id
        save_new(directory / "REQUEST.json", payload)
        save_new(directory / "INDEX.json", index)
    print("prepared 4 independent semantic review requests")


def execute(root_id: str) -> None:
    base = config()
    directory = HERE / "semantic_review" / root_id
    index = read(directory / "INDEX.json")
    payload = read(directory / "REQUEST.json")
    text, ids = prompt(root_id)
    if (index["candidate_ids"] != ids or index["prompt_sha256"] != sha(text.encode("utf-8"))
            or index["payload_sha256"] != sha(canonical(payload))
            or payload["messages"] != [{"role": "user", "content": text}]):
        raise ValueError("frozen_review_request_changed")
    if (directory / "RESPONSE.json").exists() or (directory / "ERROR.json").exists():
        raise FileExistsError("review_attempt_already_completed")
    save_new(directory / "ATTEMPT.json", {"status": "RESERVED_ONE_HTTP_ATTEMPT",
              "requested_at": datetime.now(timezone.utc).isoformat(),
              "payload_sha256": index["payload_sha256"]})
    request = urllib.request.Request(
        index["endpoint"], data=canonical(payload),
        headers={"Content-Type": "application/json", "Authorization": "Bearer " + base["secret"]},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            raw = response.read()
            http_status = response.status
    except Exception as error:
        save_new(directory / "ERROR.json", {"status": "ERROR_NO_RETRY", "error_type": type(error).__name__,
                 "error": str(error), "payload_sha256": index["payload_sha256"]})
        raise
    envelope = json.loads(raw)
    save_new(directory / "RESPONSE.json", {"status": "RESPONSE_RECEIVED", "root_id": root_id,
             "http_status": http_status, "raw_response_sha256": sha(raw),
             "payload_sha256": index["payload_sha256"], "envelope": envelope})
    print(json.dumps({"root_id": root_id, "returned_model": envelope.get("model"),
                      "usage": envelope.get("usage"), "response_sha256": sha(raw)}))


def parse_review(envelope: dict, expected_ids: list[str], expected_model: str = MODEL) -> tuple[dict[str, dict], list[str]]:
    errors = []
    if envelope.get("model") != expected_model:
        errors.append("returned_model_mismatch")
    choices = envelope.get("choices")
    if not isinstance(choices, list) or len(choices) != 1 or choices[0].get("finish_reason") != "stop":
        return {}, errors + ["choices_or_finish_reason_invalid"]
    raw_text = choices[0].get("message", {}).get("content")
    try:
        parsed = json.loads(raw_text)
    except (TypeError, ValueError):
        return {}, errors + ["review_json_invalid"]
    reviews = parsed.get("reviews") if isinstance(parsed, dict) else None
    if not isinstance(reviews, list) or len(reviews) != len(expected_ids):
        return {}, errors + ["review_count_invalid"]
    by_id = {}
    for review in reviews:
        if not isinstance(review, dict) or review.get("candidate_id") not in expected_ids:
            errors.append("review_candidate_id_invalid")
            continue
        candidate_id = review["candidate_id"]
        if candidate_id in by_id:
            errors.append("review_candidate_id_duplicate")
        by_id[candidate_id] = review
        items = review.get("items")
        if not isinstance(items, dict) or set(items) != set(LABELS):
            errors.append(f"{candidate_id}:item_verdicts_invalid")
            continue
        for label, value in items.items():
            if (not isinstance(value, dict) or type(value.get("supported")) is not bool
                    or not isinstance(value.get("reason"), str) or not value["reason"].strip()):
                errors.append(f"{candidate_id}:{label}:item_verdict_invalid")
        for field in ("coherent", "novel_vs_history", "distinct_within_batch"):
            if type(review.get(field)) is not bool:
                errors.append(f"{candidate_id}:{field}_invalid")
        if not isinstance(review.get("reason"), str) or not review["reason"].strip():
            errors.append(f"{candidate_id}:reason_invalid")
    if set(by_id) != set(expected_ids):
        errors.append("review_ids_incomplete")
    return by_id if not errors else {}, errors


def finalize() -> None:
    report = read(HERE / "REPORT.json")
    result = {"status": "AUTOMATIC_SEMANTIC_REVIEW_COMPLETED", "generator_model": report["generator_model"],
              "reviewer_provider": "TJU AI", "reviewer_model_requested": MODEL,
              "no_codex_content_review": True, "solver_calls": 0, "selected_for_training": 0,
              "roots": []}
    for suffix in ROOT_IDS:
        root_id = "cc-train-episode-" + suffix
        directory = HERE / "semantic_review" / root_id
        index = read(directory / "INDEX.json")
        response_path = directory / "RESPONSE.json"
        if not response_path.exists():
            by_id, errors, envelope = {}, ["response_missing"], {}
            response_sha = None
        else:
            response = read(response_path)
            response_sha = sha(response_path.read_bytes())
            envelope = response.get("envelope", {})
            by_id, errors = parse_review(envelope, index["candidate_ids"])
            if response.get("payload_sha256") != index["payload_sha256"]:
                errors.append("response_payload_binding_invalid")
        checks = []
        for candidate_id in index["candidate_ids"]:
            review = by_id.get(candidate_id)
            passed = bool(review and not errors and all(
                review["items"][label]["supported"] for label in LABELS
            ) and all(review[field] for field in
                      ("coherent", "novel_vs_history", "distinct_within_batch")))
            checks.append({"candidate_id": candidate_id, "semantic_pass": passed,
                           "review": review, "schema_or_binding_errors": errors})
        result["roots"].append({
            "root_id": root_id, "candidate_count": len(checks),
            "semantic_pass_count": sum(row["semantic_pass"] for row in checks),
            "reviewer_model_returned": envelope.get("model"),
            "reviewer_response_id": envelope.get("id"), "usage": envelope.get("usage"),
            "prompt_sha256": index["prompt_sha256"], "payload_sha256": index["payload_sha256"],
            "response_file_sha256": response_sha, "source_sha256": index["source_sha256"],
            "candidate_file_sha256": index["label_candidate_file_sha256"],
            "schema_or_binding_errors": errors, "checks": checks,
        })
    result["total_semantic_pass"] = sum(root["semantic_pass_count"] for root in result["roots"])
    save_new(HERE / "SEMANTIC_REVIEW.json", result)
    print(json.dumps({"semantic_pass": result["total_semantic_pass"],
                      "reviewed": sum(root["candidate_count"] for root in result["roots"])}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--prepare", action="store_true")
    group.add_argument("--execute", choices=["cc-train-episode-" + value for value in ROOT_IDS])
    group.add_argument("--finalize", action="store_true")
    args = parser.parse_args()
    if args.prepare:
        prepare()
    elif args.execute:
        execute(args.execute)
    else:
        finalize()
