"""Frozen prompts for the post-generation Qwen review and future writers."""

from __future__ import annotations

import json
from typing import Any, Iterable


MODEL = "Qwen/Qwen3.6-35B-A3B"
LABELS = tuple(f"I{i}" for i in range(1, 7))


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


ORDERING_REVIEW_INSTRUCTIONS = r"""You are an independent reviewer of six-item ordering questions generated by Qwen.
Review the supplied candidate and complete transcript. This is a conversation-order task: order the six statements by the positions where their primary clauses APPEAR IN THE SUPPLIED DIALOGUE, including left-to-right clause order within a single turn. Do not order recalled real-world events.

Return one JSON object only with a `reviews` array. You receive only the public question/items and complete transcript, without the writer's Gold, evidence or chosen anchors. Independently locate and check each item's primary clause in the transcript. Do not rely on a prior reviewer result or rewrite the question or items. Return your anchor findings; the program computes Gold from those findings.
Keep every `reason` to at most 160 characters. Use one short finding, never deliberation, a self-correction narrative, a repeated transcript or a full answer sequence. Reasons are annotations; put all decisions in the required booleans and anchors. If a reason mentions another matching occurrence, also list its exact clause in alternative_matching_anchors.

For every item I1-I6, return:
{"supported": boolean,
 "order_anchor": {"turn_ref": exact source turn ref, "quote": exact short contiguous source clause, "reason": short explanation},
 "support_refs": [exact source turn refs used only to resolve a referent or claim context],
 "alternative_matching_anchors": [{"turn_ref": exact source turn ref, "quote": exact short contiguous source clause, "reason": short explanation}],
 "actor_ok": boolean, "modality_ok": boolean, "state_ok": boolean,
 "neutral_stem_ok": boolean, "reason": short concrete reason}

`order_anchor` is exactly one primary clause for this item. It determines the item's order and must not be replaced by a contextual support ref. Several items may share a turn when their exact quoted clauses occupy separate, non-overlapping positions. Copy only the clause supporting this item, not the whole multi-clause turn. The quote must occur exactly once inside its cited turn; include enough neighboring words to identify it uniquely without overlapping another item's clause. Do not invent character offsets: the program resolves them from exact text. Identical, overlapping or unlocatable spans cannot define six ordered items.

A support ref may resolve a uniquely identifiable pronoun, actor, object, or event, but it never determines order. List every plausible alternative matching clause, including alternatives within the SAME turn and alternatives that would change the complete order. If the item is broad enough to match multiple clauses or turns, fail it or set the alternatives explicitly; do not silently choose one. Return an empty alternative_matching_anchors array only if there is no alternative.

Preserve exact actor, object, event instance, tense, state, and modality. `could`, `might`, `should`, `will`, `is`, `was`, `plans to`, `promises to`, `suggests`, `reports`, and completed actions are not interchangeable. A plan, offer, advice, intention, or capability is not completion. Contextual resolution is allowed only when the complete transcript makes one referent uniquely identifiable; never add world knowledge or an unstated detail.

At question level return:
{"candidate_id": exact ID, "items": {...},
 "coherent": boolean, "unique_order": boolean,
 "alternative_orders": [complete permutations of I1-I6, if any],
 "neutral_stem_ok": boolean, "reason": short explanation}

`coherent` means all six items fit the stem's topic. `unique_order` is false if any alternative matching clause or unresolved reference changes the order or causes overlapping/tied anchors. The stem must not reveal order with ordinal markers or by listing the answer sequence. The program, not the reviewer, recomputes Gold by source turn index and exact clause position from the six verified order anchors. Evidence shortage is not the same as an explicit contradiction: report unsupported claims precisely and do not invent a false option.
"""


ORDERING_GENERATION_INSTRUCTIONS = r"""Write six-item ordering questions by CONVERSATION APPEARANCE ORDER.
Each question has exactly: candidate_id,root_id,question_type,topic,chronology_kind,question,
items,gold,item_evidence,order_reason. question_type is ordering; chronology_kind is conversation_order.
The stem must explicitly contain 'APPEAR IN THE SUPPLIED DIALOGUE', with a narrow coherent topic.
Order primary clauses as they occur in the supplied transcript, including left-to-right clause
order within one turn, NOT dates of recalled real-world events. Make this within-turn rule clear
in the question without revealing the answer. items is {I1:text,I2:text,I3:text,I4:text,I5:text,I6:text};
six distinct concise statements with clear actors, referents and state. Do not include turn IDs,
label references, ordinal clues or invented dates in item text. Display order can be arbitrary;
evaluation applies random permutations independent of Gold.
gold is a complete permutation of I1..I6. item_evidence maps each of I1..I6 to exactly:
{turn_ref,speaker,quote,status,reason}. status is statement,report,decision,advice,offer,promise,or action.
Status is a descriptive annotation; preserve the actual modality in the statement and quotation.
Keep each reason, order_reason and abstention reason to at most 160 characters. Give one short
finding, never a deliberation or self-correction narrative. Do not repeat the transcript or walk
through the full answer in reason fields. Put final decisions in the structured fields.
The six anchors need not be in six different turns. Multiple items may share one turn when they
refer to separate, non-overlapping clauses with a clear textual order. Give each item an exact
short contiguous quote for its own clause, not the entire multi-clause turn. The quote must occur
exactly once in that turn. The program computes character offsets; do not invent offsets.
Contextual turns may clarify a unique referent but never replace its primary clause position.
Avoid broad statements repeated elsewhere in the supplied dialogue that make ordering ambiguous.
Use one coherent topic; do not pad with unrelated events or repeat one proposition to make six items.
Sort by source turn position and then clause position for Gold. An independent Qwen reviewer checks
clause anchors and the program recomputes Gold. order_reason explains textual appearance order,
not world-event chronology. Abstain if six distinct, locatable, non-overlapping items are unavailable.
"""


def build_ordering_review_prompt(root_id: str, candidates: list[dict[str, Any]],
                                 turns: list[dict[str, Any]],
                                 feedback_suffix: str = "") -> str:
    payload = {"root_id": root_id, "candidates": candidates, "source_turns": turns}
    suffix = feedback_suffix.strip()
    return (ORDERING_REVIEW_INSTRUCTIONS +
            ("\n[FEEDBACK_SUFFIX]\n" + suffix + "\n[/FEEDBACK_SUFFIX]\n" if suffix else "") +
            "\nDATA:\n" + _json(payload))


MULTISELECT_GENERATION_INSTRUCTIONS = r"""Generate source-grounded six-option multi-select question drafts from the complete supplied dialogue. Return one JSON object with `questions` and `abstentions`, and no prose outside it.

Each question must have a narrow coherent stem and between two and six correct options. Gold is the set of all options directly supported by the dialogue; cardinality may be 2, 3, 4, 5, or 6. Do not force a cardinality, prefix-shaped labels, or a desired position pattern. Preserve the original generated option order in the raw record; a later evaluator may apply a reproducible random display permutation and remap Gold.

For each option provide a complete proposition, exact source turn references, exact contiguous quotes, speaker, and a rationale. Contextual references may be used when the complete transcript uniquely resolves them. Evidence shortage is not evidence of contradiction: do not label an option false merely because the dialogue is silent. Use `contradicts` only for an explicit source statement by the same actor or event scope. Do not add a semantic admission gate beyond schema, source binding, quote validity, and the downstream review policy. If the source cannot support a whole question, abstain instead of padding it.
"""


def build_multiselect_generation_prompt(root_id: str, source: dict[str, Any],
                                        candidate_ids: Iterable[str],
                                        feedback_suffix: str = "") -> str:
    payload = {"root_id": root_id, "candidate_ids": list(candidate_ids), "source": source}
    suffix = feedback_suffix.strip()
    return (MULTISELECT_GENERATION_INSTRUCTIONS +
            ("\n[FEEDBACK_SUFFIX]\n" + suffix + "\n[/FEEDBACK_SUFFIX]\n" if suffix else "") +
            "\nDATA:\n" + _json(payload))
